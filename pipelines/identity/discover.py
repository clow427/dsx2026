"""Alumni discovery from ORCID and OpenBU (identity-resolution Req 1.1-1.4, 4.1).

Writes data/curation/people.discovered.yaml: generated entries in the same
format as the hand-curated data/curation/people.yaml, which the directory step
loads alongside it. Hand-curated entries always win (an ORCID or slug already
in people.yaml is skipped here).

An entry is created only for a person who is already in a module graph and is
tied to a BU degree by a unique identifier:

  * ORCID: the ORCID on a source-level person (research.json, innovation.json)
    has a public ORCID education entry stating a completed BU degree
    (orcid_education.bu_degrees), and/or
  * OpenBU: a BU thesis or dissertation lists that same ORCID (openbu.Thesis.orcid).

Each entry is `verified_alumnus` with the degree, department, and graduation
year of the most recent stated BU degree, and cites every stated BU degree as
evidence. The matcher then merges the entry with its source-level records on
ORCID (merged/high), so no name matching is involved. Theses without an ORCID
are counted but not used: a name alone would only ever give a low-confidence
candidate, and it can't prove which person wrote the thesis.

Run:
    python -m pipelines.identity.run --step discover
"""

from __future__ import annotations

import json
import re
from collections import Counter
from dataclasses import dataclass, field
from pathlib import Path
from typing import Iterable

import yaml

from pipelines.common.contract import REPO_ROOT

from .normalize_names import strip_accents
from .openbu import Thesis
from .orcid_education import ORCID_RE, OrcidDegree, bu_degrees

DISCOVERED_PATH = REPO_ROOT / "data" / "curation" / "people.discovered.yaml"

HEADER = """\
# GENERATED by `python -m pipelines.identity.run --step discover`. Do not edit by hand:
# add or correct people in data/curation/people.yaml instead (hand-curated entries win).
#
# Each entry is a person already in a module graph whose ORCID iD is tied to a
# completed Boston University degree by a public source:
#   user_submitted -> the person's public ORCID record (education entry)
#   bu_repository  -> an OpenBU thesis/dissertation that lists the same ORCID
# Degree, department, and graduation year come from the most recent stated BU degree.
"""


@dataclass
class DiscoverStats:
    orcids_checked: int = 0
    orcid_records_with_bu_degree: int = 0
    theses: int = 0
    theses_with_orcid: int = 0
    theses_linked: int = 0
    entries: int = 0
    skipped: Counter = field(default_factory=Counter)


def slugify(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", strip_accents(text).lower()).strip("-")


def source_orcids(docs: Iterable[dict]) -> dict[str, str]:
    """ORCID -> display name of the first source-level person carrying it (sorted by node id)."""
    out: dict[str, str] = {}
    for doc in docs:
        for node in sorted(doc.get("nodes", []), key=lambda n: n["id"]):
            orcid = str((node.get("attributes") or {}).get("orcid") or "").upper()
            if node.get("type") == "person" and not node["id"].startswith("person:canonical:") and ORCID_RE.fullmatch(orcid):
                out.setdefault(orcid, node["label"])
    return out


@dataclass(frozen=True)
class _Degree:
    year: int
    degree: str
    department: str | None
    source: str
    url: str
    note: str


def _degrees(orcid: str, educations: dict, theses: list[Thesis], this_year: int | None) -> list[_Degree]:
    out = [_Degree(t.year, t.degree, t.discipline, "bu_repository", t.handle_url, t.note()) for t in theses]
    from_orcid: list[OrcidDegree] = bu_degrees(orcid, educations, this_year)
    if from_orcid:
        # One ref per ORCID record (refs dedupe on URL), listing every BU degree it states.
        note = "; ".join(d.note().removeprefix("ORCID education entry: ") for d in from_orcid)
        latest = from_orcid[-1]
        out.append(_Degree(latest.year, latest.degree, latest.department, "user_submitted", latest.url,
                           f"ORCID education entries: {note}"))
    return out


def discover(
    docs: list[dict],
    curated: list[dict],
    educations: dict[str, dict],
    theses: list[Thesis],
    this_year: int | None = None,
) -> tuple[list[dict], DiscoverStats]:
    stats = DiscoverStats(theses=len(theses))
    people = source_orcids(docs)
    curated_orcids = {str(e.get("orcid") or "").upper() for e in curated}
    used_slugs = {e.get("slug") for e in curated}

    theses_by_orcid: dict[str, list[Thesis]] = {}
    for t in theses:
        if t.orcid:
            stats.theses_with_orcid += 1
            theses_by_orcid.setdefault(t.orcid, []).append(t)

    entries: list[dict] = []
    for orcid, name in sorted(people.items()):
        stats.orcids_checked += 1
        linked = theses_by_orcid.get(orcid, [])
        degrees = _degrees(orcid, educations.get(orcid) or {}, linked, this_year)
        if any(d.source == "user_submitted" for d in degrees):
            stats.orcid_records_with_bu_degree += 1
        if not degrees:
            continue
        if orcid in curated_orcids:
            stats.skipped["already_hand_curated"] += 1
            continue
        stats.theses_linked += len(linked)
        latest = max(degrees, key=lambda d: (d.year, d.source == "bu_repository"))
        slug = f"{slugify(name)}-{orcid[-4:].lower()}"
        if not slugify(name) or slug in used_slugs:
            stats.skipped["slug_unavailable"] += 1
            continue
        used_slugs.add(slug)
        bu: dict = {"status": "verified_alumnus", "degree": latest.degree}
        if latest.department:
            bu["department"] = latest.department
        bu["graduation_year"] = latest.year
        bu["evidence"] = [
            {"source": d.source, "url": d.url, "note": d.note}
            for d in sorted(degrees, key=lambda d: (d.source != "bu_repository", d.year, d.url))
        ]
        entries.append({
            "slug": slug,
            "name": name,
            "orcid": orcid,
            "bu": bu,
            "submitted_by": bu["evidence"][0]["source"],
            "discovered_by": sorted({"openbu" if d.source == "bu_repository" else "orcid" for d in degrees}),
        })
    stats.entries = len(entries)
    return entries, stats


def write_discovered(entries: list[dict], path: Path = DISCOVERED_PATH) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    body = yaml.safe_dump(entries, sort_keys=False, allow_unicode=True, width=120) if entries else "[]\n"
    path.write_text(HEADER + "\n" + body, encoding="utf-8")
    return path


def load_docs(paths: Iterable[Path]) -> list[dict]:
    return [json.loads(Path(p).read_text(encoding="utf-8")) for p in paths if Path(p).exists()]
