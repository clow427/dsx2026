"""Property-based tests for the shared contract helpers and validator (Hypothesis).

Each test names the correctness property it checks. The properties are listed in
`.kiro/specs/shared-data-contract/design.md` under "Correctness properties".

All generated records are fictional (MOCK) and use example.org URLs.
"""

from __future__ import annotations

import copy
import re

from hypothesis import assume, example, given
from hypothesis import strategies as st

from pipelines.common.contract import EDGE_ENDPOINTS, NODE_TYPES, SYMMETRIC_EDGE_TYPES
from pipelines.common.graph import GraphBuilder
from pipelines.common.ids import make_edge_id, make_node_id, parse_node_id
from pipelines.common.sources import merge_refs, ref_key
from pipelines.common.validation import validate_graph

GENERATED_AT = "2026-10-24T00:00:00Z"

namespaces = st.from_regex(r"[a-z0-9_]{1,8}", fullmatch=True)
local_ids = st.from_regex(r"[A-Za-z0-9._-]{1,12}", fullmatch=True)
node_types = st.sampled_from(sorted(NODE_TYPES))
labels = st.text(min_size=1, max_size=20)


@st.composite
def refs(draw, source: str = "manual_curation") -> dict:
    record_id = draw(local_ids)
    return {"source": source, "record_id": record_id, "url": f"https://example.org/records/{record_id}", "note": "MOCK"}


ref_lists = st.lists(refs(), min_size=1, max_size=4, unique_by=ref_key)


@st.composite
def affiliations(draw) -> dict:
    status = draw(st.sampled_from(["verified_alumnus", "bu_affiliated_researcher", "unverified", "ambiguous"]))
    needs_evidence = status in ("verified_alumnus", "bu_affiliated_researcher")
    source = "bu_repository" if status == "verified_alumnus" else "openalex"
    evidence = draw(st.lists(refs(source), min_size=1 if needs_evidence else 0, max_size=3, unique_by=ref_key))
    return {"status": status, "evidence": evidence}


def _node_key_id(key: tuple[str, str, str]) -> str:
    # A named function, not a lambda: Hypothesis 6.170.9 regex-parses lambda source in `unique_by`
    # and crashes on `(*`.
    return make_node_id(*key)


@st.composite
def graph_specs(draw) -> tuple[list[dict], list[tuple]]:
    """Nodes plus edge calls (type, source, target, evidence, confidence, derivation) with valid endpoints."""
    keys = draw(
        st.lists(st.tuples(node_types, namespaces, local_ids), min_size=1, max_size=12, unique_by=_node_key_id)
    )
    nodes = []
    for node_type, namespace, local_id in keys:
        node = {"id": make_node_id(node_type, namespace, local_id), "type": node_type, "label": draw(labels),
                "sources": draw(ref_lists)}
        if node_type == "person":
            node["bu_affiliation"] = draw(affiliations())
        nodes.append(node)

    # Confidence and derivation are fixed per edge so that repeated adds only differ in evidence.
    edge_meta: dict[str, tuple[str, str]] = {}
    calls = []
    for _ in range(draw(st.integers(0, 20))):
        edge_type = draw(st.sampled_from(sorted(EDGE_ENDPOINTS)))
        sources = [n["id"] for n in nodes if n["type"] in EDGE_ENDPOINTS[edge_type][0]]
        targets = [n["id"] for n in nodes if n["type"] in EDGE_ENDPOINTS[edge_type][1]]
        if not sources or not targets:
            continue
        source, target = draw(st.sampled_from(sources)), draw(st.sampled_from(targets))
        if source == target:
            continue
        edge_id = make_edge_id(edge_type, source, target)
        if edge_id not in edge_meta:
            edge_meta[edge_id] = (draw(st.sampled_from(["high", "medium", "low"])),
                                  draw(st.sampled_from(["source_record", "derived", "identity_match"])))
        calls.append((edge_type, source, target, draw(ref_lists), *edge_meta[edge_id]))
    return nodes, calls


def build(nodes: list[dict], calls: list[tuple]) -> dict:
    g = GraphBuilder()
    for node in nodes:
        # Add each node in two halves to exercise source union.
        half = max(1, len(node["sources"]) // 2)
        for chunk in (node["sources"][:half], node["sources"][half:]):
            if chunk:
                g.add_node(node["id"], node["type"], node["label"], chunk, bu_affiliation=node.get("bu_affiliation"))
    for call in calls:
        g.add_edge(*call)
    return g.to_document("mock", generated_at=GENERATED_AT, notes="MOCK: generated by Hypothesis")


# --- IDs -------------------------------------------------------------------


@given(node_types, namespaces, local_ids)
def test_node_id_round_trips(node_type, namespace, local_id):
    """Property C1: parse_node_id(make_node_id(t, ns, id)) == (t, ns, id), and the source casing is kept."""
    node_id = make_node_id(node_type, namespace, local_id)
    assert parse_node_id(node_id) == (node_type, namespace, local_id)


# Mostly-valid characters plus the boundary cases that matter for IDs: separators, whitespace,
# a trailing newline, and non-ASCII. Plain st.text() almost never produces "A1\n".
id_ish_text = st.text(alphabet=st.sampled_from(list("Aa0_.-") + ["\n", " ", ":", "/", "é", "|"]), max_size=8)


@given(id_ish_text)
@example("0\n")  # falsifying example Hypothesis found before ids.py switched to fullmatch()
def test_make_node_id_accepts_exactly_contract_local_ids(local_id):
    """Property C2: an ID is built only when local_id fully matches the contract; otherwise ValueError, never a rewrite."""
    valid = re.fullmatch(r"[A-Za-z0-9._-]+", local_id) is not None
    try:
        node_id = make_node_id("person", "openalex", local_id)
    except ValueError:
        assert not valid
    else:
        assert valid and node_id == f"person:openalex:{local_id}"


@given(id_ish_text.map(str.lower))
@example("0\n")
def test_make_node_id_accepts_exactly_contract_namespaces(namespace):
    """Property C2 (namespace half)."""
    valid = re.fullmatch(r"[a-z0-9_]+", namespace) is not None
    try:
        make_node_id("topic", namespace, "T1")
    except ValueError:
        assert not valid
    else:
        assert valid


@given(st.sampled_from(sorted(EDGE_ENDPOINTS)), local_ids, local_ids)
def test_edge_id_is_order_independent_only_for_symmetric_types(edge_type, a, b):
    """Property C3: symmetric edge IDs ignore endpoint order; directed edge IDs keep it."""
    assume(a != b)
    s, t = f"person:openalex:{a}", f"person:openalex:{b}"
    if edge_type in SYMMETRIC_EDGE_TYPES:
        assert make_edge_id(edge_type, s, t) == make_edge_id(edge_type, t, s)
    else:
        assert make_edge_id(edge_type, s, t) != make_edge_id(edge_type, t, s)


# --- Provenance merging ----------------------------------------------------


@given(st.lists(refs(), max_size=6, unique_by=ref_key), st.lists(refs(), max_size=6))
def test_merge_refs_is_a_deduplicated_union(existing, new):
    """Property C4: merge keeps existing refs in order, adds each new key once, and is idempotent."""
    merged = merge_refs(existing, new)
    keys = [ref_key(r) for r in merged]
    assert merged[: len(existing)] == existing
    assert len(keys) == len(set(keys))
    assert set(keys) == {ref_key(r) for r in existing + new}
    assert merge_refs(merged, new) == merged


# --- GraphBuilder output ---------------------------------------------------


@given(graph_specs())
def test_builder_output_passes_validator(spec):
    """Property C5: any graph built through GraphBuilder from valid parts has zero validator errors."""
    doc = build(*spec)
    result = validate_graph(doc)
    assert result.errors == []
    assert [n["id"] for n in doc["nodes"]] == sorted(n["id"] for n in doc["nodes"])
    assert [e["id"] for e in doc["edges"]] == sorted(e["id"] for e in doc["edges"])


@given(graph_specs(), st.randoms(use_true_random=False))
def test_builder_output_is_independent_of_insertion_order(spec, rnd):
    """Property C6: shuffling the order of node and edge adds yields a byte-identical document."""
    nodes, calls = spec
    shuffled_nodes, shuffled_calls = list(nodes), list(calls)
    rnd.shuffle(shuffled_nodes)
    rnd.shuffle(shuffled_calls)
    assert build(nodes, calls) == build(shuffled_nodes, shuffled_calls)


@given(graph_specs())
def test_builder_unions_sources_and_evidence(spec):
    """Property C7: every source given for a node and every evidence ref given for an edge survives the build."""
    nodes, calls = spec
    doc = build(nodes, calls)
    out_nodes = {n["id"]: n for n in doc["nodes"]}
    for node in nodes:
        assert {ref_key(r) for r in out_nodes[node["id"]]["sources"]} == {ref_key(r) for r in node["sources"]}
    out_edges = {e["id"]: e for e in doc["edges"]}
    for edge_type, source, target, evidence, *_ in calls:
        got = {ref_key(r) for r in out_edges[make_edge_id(edge_type, source, target)]["evidence"]}
        assert {ref_key(r) for r in evidence} <= got


# --- Validator rejects broken graphs ---------------------------------------


def _with_edge(spec):
    nodes, calls = spec
    assume(calls)
    return build(nodes, calls)


@given(graph_specs(), st.data())
def test_validator_rejects_dangling_edges(spec, data):
    """Property C8: removing any node that an edge references produces a 'references missing node' error."""
    doc = _with_edge(spec)
    edge = data.draw(st.sampled_from(doc["edges"]))
    missing = data.draw(st.sampled_from([edge["source"], edge["target"]]))
    doc["nodes"] = [n for n in doc["nodes"] if n["id"] != missing]
    errors = validate_graph(doc).errors
    assert any(f"references missing node {missing}" in e for e in errors)


@given(graph_specs(), st.data())
def test_validator_rejects_duplicate_node_ids(spec, data):
    """Property C9: a repeated node ID is always an error."""
    doc = build(*spec)
    node = data.draw(st.sampled_from(doc["nodes"]))
    doc["nodes"].append(copy.deepcopy(node))
    assert any(f"duplicate node id: {node['id']}" in e for e in validate_graph(doc).errors)


@given(graph_specs(), st.data())
def test_validator_rejects_edges_without_evidence(spec, data):
    """Property C10: an edge with no evidence fails validation."""
    doc = _with_edge(spec)
    edge = data.draw(st.sampled_from(doc["edges"]))
    edge["evidence"] = []
    assert not validate_graph(doc).ok


@given(graph_specs(), st.data())
def test_validator_rejects_affiliation_status_without_evidence(spec, data):
    """Property C11: verified_alumnus and bu_affiliated_researcher always need at least one evidence record."""
    doc = build(*spec)
    people = [n for n in doc["nodes"] if n["type"] == "person"]
    assume(people)
    person = data.draw(st.sampled_from(people))
    person["bu_affiliation"] = {
        "status": data.draw(st.sampled_from(["verified_alumnus", "bu_affiliated_researcher"])),
        "evidence": [],
    }
    assert not validate_graph(doc).ok


@given(graph_specs(), st.data(), st.sampled_from(["\n", " ", ":", "/", "é"]))
def test_validator_rejects_node_ids_with_characters_outside_the_contract(spec, data, suffix):
    """Property C12: a node ID that doesn't fully match the contract pattern is an error, even if every
    edge that references it is updated consistently (so no dangling-edge error masks it)."""
    doc = build(*spec)
    node = data.draw(st.sampled_from(doc["nodes"]))
    old, new = node["id"], node["id"] + suffix
    node["id"] = new
    for edge in doc["edges"]:
        for end in ("source", "target"):
            if edge[end] == old:
                edge[end] = new
    assert not validate_graph(doc).ok
